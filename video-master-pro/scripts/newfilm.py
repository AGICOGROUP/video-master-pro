"""Scaffold a project from a footage folder — no code editing, no host paths.

    python newfilm.py --src "D:\\footage" --shots 8 --duration 40 --aspect 16:9
    python newfilm.py --src ./footage --aspect 9:16 --shots 7 --duration 40 --voice en-US-BrianMultilingualNeural

It probes every clip, spreads the requested number of cuts across the longest
material (avoiding the first/last 8 % where cameras get switched on and off),
and writes $FILM_WORK/spec_local.py with placeholder copy for you to fill in.
Every in-point it picks is a *guess*: run `preview.py` afterwards and correct
any cut whose picture does not match the line you wrote for it.
"""
import argparse
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from paths import P, require_src  # noqa: E402

VIDEO = (".mp4", ".mov", ".m4v", ".avi", ".mkv")
LAYOUTS = ["hero", "left", "right", "side"]


def probe(p):
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries",
                        "format=duration:stream=width,height",
                        "-of", "csv=p=0:nk=1", str(p)],
                       capture_output=True, text=True, errors="replace")
    if r.returncode != 0:
        return None
    vals = [v for v in r.stdout.replace(",", "\n").split() if v]
    try:
        dur = float(vals[-1])
        w, h = int(vals[0]), int(vals[1])
    except (ValueError, IndexError):
        return None
    return dict(dur=dur, w=w, h=h)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src")
    ap.add_argument("--shots", type=int, default=8)
    ap.add_argument("--duration", type=float, default=40.0)
    ap.add_argument("--aspect", default="16:9", choices=["16:9", "9:16"])
    ap.add_argument("--voice", default="en-US-AndrewMultilingualNeural")
    ap.add_argument("--title", default="Untitled film")
    ap.add_argument("--proj", default="film01")
    ap.add_argument("--bpm", type=float, default=104.0)
    ap.add_argument("--root", type=float, default=110.0)
    ap.add_argument("--seed", type=int, default=7)
    a, _ = ap.parse_known_args()   # --work/--out/--src are also read by paths.py

    src = require_src(Path(a.src) if a.src else None)
    clips = []
    for p in sorted(src.rglob("*")):
        if p.suffix.lower() in VIDEO:
            info = probe(p)
            if info and info["dur"] >= 3.0:
                clips.append((p.relative_to(src).as_posix(), info))
    if not clips:
        sys.exit(f"[newfilm] no usable video files under {src}")
    clips.sort(key=lambda c: -c[1]["dur"])

    n = max(3, a.shots)
    picks = []
    for i in range(n):
        rel, info = clips[i % len(clips)]
        usable = max(0.0, info["dur"] * 0.84 - 1.0)
        start = round(info["dur"] * 0.08 + usable * ((i // len(clips) + 1) / (n // len(clips) + 2)), 2)
        start = min(start, max(0.0, info["dur"] - 2.0))
        picks.append((rel, start))

    slot = round(a.duration / n, 3)
    durs = [slot] * n
    durs[-1] = round(a.duration - slot * (n - 1), 3)

    w, h = (1920, 1080) if a.aspect == "16:9" else (1080, 1920)
    # --out is the output *folder* (resolved by paths.py); the file name is derived.
    out_name = f"{a.proj}_{a.aspect.replace(':', 'x')}.mp4"
    lines = [
        '"""Generated by newfilm.py — edit the copy, keep the schema."""',
        "SPECS = {",
        '    "A": dict(',
        '        key="A",',
        f'        proj="{a.proj}",',
        f'        title="{a.title}",',
        f'        out="{out_name}",',
        f'        voice="{a.voice}",',
        f"        duration={a.duration},",
        f"        w={w}, h={h}, fps=30,",
        '        accent="#E8A33D",',
        '        base="#0A0D0F",',
        '        ink="#C3CDD3",',
        f"        music=dict(root={a.root}, bpm={a.bpm}, seed={a.seed}, bright=1.0, perc=1.0),",
        "        shots=[",
    ]
    for i, ((rel, start), d) in enumerate(zip(picks, durs)):
        layout = "endcard" if i == n - 1 else LAYOUTS[i % len(LAYOUTS)]
        lines += [
            f"            dict(layout='{layout}', src={rel!r}, start={start}, dur={d},",
            f"                 align='50% 50%', drift='in', ch='{i + 1:02d}', "
            f"eyebrow='BRAND  ·  PRODUCT',",
            "                 cn='中文主标题', en='English headline',",
        ]
        if layout == "endcard":
            lines += [
                '                 rows=[("第一项", "first row"), ("第二项", "second row")],',
                '                 cta_cn="欢迎来厂考察与选型", '
                'cta_en="Visit our factory, or send your inquiry",',
            ]
        lines += ["                 vo='One sentence of narration for this shot.'),"]
    lines += ["        ],", "    ),", "}", ""]

    dst = P.work / "spec_local.py"
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("\n".join(lines), encoding="utf-8")

    print(f"wrote {dst}")
    print(f"  {n} shots x {slot:.1f}s, canvas {w}x{h}, {len(clips)} source clips scanned")
    for i, ((rel, start), d) in enumerate(zip(picks, durs), 1):
        print(f"  {i:02d} {rel}  @ {start}s  {d}s")
    print("\nNext:")
    print(f"  1  edit {dst} — real lines, real in-points, real eyebrow")
    print(f"  2  python preview.py --src \"{src}\"   # check every cut against its line")
    print("  3  python build.py A && python overlay_gen.py A && python audio.py A && python compose.py A")
    print("  4  python verify.py <out.mp4>")


if __name__ == "__main__":
    main()
